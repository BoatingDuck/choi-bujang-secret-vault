import assert from 'node:assert/strict';
import { SAFE_POLICY, policyDigest, comparePolicy, restoreTestPolicy } from '../src/policy-recovery.mjs';
import { noteDigest, verifyPrivateNoteSnapshot } from '../src/note-recovery.mjs';
const backup = structuredClone(SAFE_POLICY);
const hash = policyDigest(backup);
const current = { ...backup, select: 'true', anotherService: 'keep' };
assert.deepEqual(comparePolicy(backup, current, hash).changes, ['select']);
assert.equal(restoreTestPolicy(backup, current, hash).applied, false);
const restored = restoreTestPolicy(backup, current, hash, true);
assert.equal(restored.policy.select, backup.select);
assert.equal(restored.policy.anotherService, 'keep');
assert.equal(current.select, 'true');
assert.throws(() => comparePolicy({ ...backup, select: 'true' }, current, hash));
const note = { id: '11111111-1111-4111-8111-111111111111', ownerId: '22222222-2222-4222-8222-222222222222', title: 'test', body: 'fixture only' };
note.sha256 = noteDigest(note);
assert.equal(verifyPrivateNoteSnapshot(note, note.id, note.ownerId).id, note.id);
assert.throws(() => verifyPrivateNoteSnapshot(note, note.id, '33333333-3333-4333-8333-333333333333'));
assert.throws(() => verifyPrivateNoteSnapshot({ ...note, body: 'tampered' }, note.id, note.ownerId));
console.log('PASS: test policy preview, verification, isolated restore, unchanged other service');
console.log('PASS: one-note identity/owner/hash checks, tamper rejected');
